  function getLang() {
    return localStorage.getItem(LANG_KEY) === "en" ? "en" : "th";
  }
  function setLang(l) {
    localStorage.setItem(LANG_KEY, l === "en" ? "en" : "th");
  }
  function t(key) {
    const dict = I18N[getLang()] || I18N.th;
    if (dict[key] != null) return dict[key];
    if (I18N.th[key] != null) return I18N.th[key];
    return key;
  }

  function applyI18n() {
    const lang = getLang();
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    const sw = document.getElementById("langToggle");
    if (sw) sw.setAttribute("data-lang", lang);
    if (typeof window.initYear === "function") window.initYear();
  }

  function toggleLang() {
    setLang(getLang() === "th" ? "en" : "th");
    applyI18n();
    if (typeof window.onLangChange === "function") window.onLangChange();
  }

  window.i18n = { t, getLang, setLang, applyI18n, toggleLang };
  window.t = t;

  document.addEventListener("DOMContentLoaded", () => {
    const btn = document.getElementById("langToggle");
    if (btn) btn.addEventListener("click", toggleLang);
    applyI18n();
  });
